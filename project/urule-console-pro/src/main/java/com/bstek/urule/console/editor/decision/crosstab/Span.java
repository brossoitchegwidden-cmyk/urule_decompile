package com.bstek.urule.console.editor.decision.crosstab;

class Span {
   private int row;
   private int col;

   public int getRow() {
      return this.row;
   }

   public void setRow(int number) {
      this.row = number;
   }

   public int getCol() {
      return this.col;
   }

   public void setCol(int number) {
      this.col = number;
   }
}
